function javaMemory(settings, fallback = { min: '4G', max: '8G' }) {
  return `-Xms${settings.java?.minMemory ?? fallback.min} -Xmx${settings.java?.maxMemory ?? fallback.max}`
}

function shellHeader() {
  return '#!/usr/bin/env bash\nset -euo pipefail\ncd "$(dirname "$0")"\n\n'
}

function batHeader() {
  return '@echo off\r\ncd /d "%~dp0"\r\n\r\n'
}

function startScripts(kind, options) {
  const { settings, fileName, neoforgeArgsPath } = options
  const memory = kind === 'velocity' ? javaMemory({ java: { minMemory: '1G', maxMemory: '2G' } }) : javaMemory(settings)
  if (kind === 'neoforge') {
    const argsPath = neoforgeArgsPath ?? 'libraries/net/neoforged/neoforge/NEOFORGE_VERSION/unix_args.txt'
    const sh = `${shellHeader()}NEOFORGE_ARGS=${argsPath}
if [ ! -f "$NEOFORGE_ARGS" ]; then
  echo "未找到 $NEOFORGE_ARGS"
  echo "请先运行 NeoForge 安装器：java -jar neoforge-*-installer.jar --installServer"
  exit 1
fi
exec java @user_jvm_args.txt @"$NEOFORGE_ARGS" "$@"
`
    const bat = `${batHeader()}set "NEOFORGE_ARGS=${argsPath.replace(/\//g, '\\')}"
if not exist "%NEOFORGE_ARGS%" (
  echo Please run the NeoForge installer first: java -jar neoforge-*-installer.jar --installServer
  exit /b 1
)
java @user_jvm_args.txt @"%NEOFORGE_ARGS%" %*
`
    return { sh, bat }
  }
  if (kind === 'velocity') {
    return {
      sh: `${shellHeader()}exec java ${memory} -jar ${fileName} "$@"\n`,
      bat: `${batHeader()}java ${memory} -jar ${fileName} %*\r\n`,
    }
  }
  return {
    sh: `${shellHeader()}exec java ${memory} ${AIKAR_FLAGS} -jar ${fileName} --nogui "$@"\n`,
    bat: `${batHeader()}java ${memory} ${AIKAR_FLAGS} -jar ${fileName} --nogui %*\r\n`,
  }
}

async function writeText(dir, relativePath, content, overwrite) {
  const absolutePath = join(dir, relativePath)
  await mkdir(dirname(absolutePath), { recursive: true })
  try {
    const existing = await readFile(absolutePath, 'utf8')
    if (existing === content) return { path: relativePath, status: 'unchanged' }
    if (!overwrite) return { path: relativePath, status: 'skipped' }
    await writeFile(absolutePath, content, 'utf8')
    return { path: relativePath, status: 'updated' }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
    await writeFile(absolutePath, content, 'utf8')
    return { path: relativePath, status: 'created' }
  }
}

async function writeBinary(dir, relativePath, bytes, overwrite) {
  const absolutePath = join(dir, relativePath)
  await mkdir(dirname(absolutePath), { recursive: true })
  let existed = false
  try {
    await readFile(absolutePath)
    existed = true
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  if (existed && !overwrite) return { path: relativePath, status: 'skipped' }
  await writeFile(absolutePath, bytes)
  return { path: relativePath, status: existed ? 'updated' : 'created' }
}

function sha256Of(buffer) {
  return createHash('sha256').update(buffer).digest('hex')
}

async function downloadJar(config, signal, dir, url, fileName, overwrite, expectedSha256, written, notes) {
  try {
    const bytes = await getBytes(url, { config, signal, timeoutMs: 180000 })
    if (expectedSha256) {
      const actual = sha256Of(bytes)
      if (actual !== expectedSha256) throw new Error(`sha256 校验失败（期望 ${expectedSha256}，实际 ${actual}）`)
    }
    written.push(await writeBinary(dir, fileName, bytes, overwrite))
    return true
  } catch (error) {
    notes.push(`下载 ${fileName} 失败：${error.message}；可手动从 ${url} 获取`)
    return false
  }
}

/**
 * Generate a server directory skeleton.
 * @param {object} config plugin config
 * @param {object} opts {kind, dir, settings, overwrite, downloadJar, gameVersion, loaderVersion, velocityVersion, arclightVariant}
 */
export async function generateServerConfig(config, opts, signal) {
  const {
    kind,
    dir,
    settings: userSettings = {},
    overwrite = false,
    downloadJar: downloadJarOption = false,
    gameVersion = config.defaultGameVersion ?? '1.21.1',
  } = opts
  if (!SERVER_KINDS.includes(kind)) throw new Error(`未知的服务端类型 "${kind}"，可选：${SERVER_KINDS.join(', ')}`)
  if (!dir) throw new Error('缺少输出目录 dir')

  const settings = deepMerge(DEFAULT_SETTINGS, userSettings)
  const written = []
  const notes = []
  await mkdir(dir, { recursive: true })

  if (kind === 'velocity') {
    const proxy = settings.proxy ?? {}
    // Keep an existing forwarding.secret so regenerating configs never silently breaks the proxy link.
    let existingSecret
    try {
      existingSecret = (await readFile(join(dir, 'forwarding.secret'), 'utf8')).trim()
    } catch {
      existingSecret = undefined
    }
    const secret = proxy.velocitySecret || existingSecret || randomBytes(24).toString('base64url')
    let velocityVersion = opts.velocityVersion
    let velocityJar = 'velocity.jar'
    if (downloadJarOption) {
      try {
        if (!velocityVersion) {
          const project = await paperProjectVersions(config, 'velocity', signal)
          velocityVersion = project.versions.find((item) => !item.includes('SNAPSHOT')) ?? project.versions[0]
        }
        if (velocityVersion) {
          const builds = await velocityBuilds(config, velocityVersion, signal)
          const build = builds[0]
          if (build?.url) {
            velocityJar = build.name ?? velocityJar
            await downloadJar(config, signal, dir, build.url, velocityJar, overwrite, build.sha256, written, notes)
          }
        }
      } catch (error) {
        notes.push(`Velocity 构建解析失败：${error.message}`)
      }
    }
    if (velocityJar === 'velocity.jar') {
      notes.push('未下载 Velocity 可执行 jar；请把下载的 velocity-*.jar 重命名为 velocity.jar，或修改 start 脚本中的文件名。')
    }
    written.push(await writeText(dir, 'velocity.toml', velocityToml(settings, velocityVersion), overwrite))
    written.push(await writeText(dir, 'forwarding.secret', `${secret}\n`, overwrite))
    if (existingSecret && !proxy.velocitySecret) notes.push('沿用了已有的 forwarding.secret（未显式传 velocitySecret）。')
    const scripts = startScripts('velocity', { settings, fileName: velocityJar })
    written.push(await writeText(dir, 'start.sh', scripts.sh, overwrite))
    written.push(await writeText(dir, 'start.bat', scripts.bat, overwrite))
    notes.push('后端服务器需设置 server.properties online-mode=false，并配置 paper-global.yml proxies.velocity 或 spigot.yml settings.bungeecord。')
    notes.push(`转发密钥（forwarding.secret / proxies.velocity.secret）：${secret} — 生成后端配置时请把同一个值传给 settings.proxy.velocitySecret。`)
    written.push(await writeText(dir, '.gitignore', 'logs/\n*.jar\n*.log\nforwarding.secret\n', overwrite))
    return { dir, kind, gameVersion, files: written, notes: [...new Set(notes)] }
  }

  written.push(await writeText(dir, 'eula.txt', eulaText(), overwrite))
  written.push(await writeText(dir, 'server.properties', serverProperties(settings, gameVersion), overwrite))
  written.push(await writeText(dir, 'whitelist.json', '[]\n', overwrite))
  written.push(
    await writeText(
      dir,
      '.gitignore',
      'logs/\ncrash-reports/\nworld*/\nbanned-*.json\neula.txt\nlibraries/\ncache/\n*.jar\n*.log\n',
      overwrite,
    ),
  )
  notes.push('EULA 已预置为 eula=true（Minecraft EULA: https://aka.ms/MinecraftEULA）；请确认你同意该协议。')

  const proxy = settings.proxy ?? {}
  let fileName = 'server.jar'
  let neoforgeArgsPath

  if (kind === 'paper' || kind === 'arclight') {
    written.push(await writeText(dir, 'bukkit.yml', bukkitYml(), overwrite))
    written.push(await writeText(dir, 'spigot.yml', spigotYml(settings), overwrite))
    written.push(await writeText(dir, 'commands.yml', commandsYml(), overwrite))
    if (proxy.enabled) {
      // Preserve the backend secret already present in paper-global.yml unless one is passed explicitly.
      let existingPaperSecret
      try {
        const existing = await readFile(join(dir, 'config/paper-global.yml'), 'utf8')
        existingPaperSecret = existing.match(/secret:\s*'([^']+)'/)?.[1]
      } catch {
        existingPaperSecret = undefined
      }
      const secret = proxy.velocitySecret || existingPaperSecret || randomBytes(24).toString('base64url')
      written.push(await writeText(dir, 'config/paper-global.yml', paperGlobalYml(secret), overwrite))
      notes.push('已生成 Velocity 现代转发配置：paper-global.yml 的 proxies.velocity + server.properties online-mode=false。')
      notes.push(`Velocity 转发密钥已写入 config/paper-global.yml，forwarding.secret 需与代理端保持一致：${secret}`)
    } else {
      notes.push('未启用代理模式；首次启动 Paper 时会自动生成 config/paper-*.yml。')
    }
  }

  if (kind === 'neoforge') {
    const neoforgeVersion = opts.loaderVersion ?? (await neoforgeVersions(config, gameVersion, signal, 1)).items[0]?.version
    if (!neoforgeVersion) throw new Error(`无法确定 NeoForge ${gameVersion} 的版本，请显式传入 loaderVersion`)
    neoforgeArgsPath = `libraries/net/neoforged/neoforge/${neoforgeVersion}/unix_args.txt`
    written.push(
      await writeText(dir, 'user_jvm_args.txt', `# NeoForge JVM 参数（每行一个参数）\n${javaMemory(settings)}\n`, overwrite),
    )
    notes.push(`NeoForge 版本：${neoforgeVersion}（Minecraft ${gameVersion}）。`)
    if (downloadJarOption) {
      const url = `https://maven.neoforged.net/releases/net/neoforged/neoforge/${neoforgeVersion}/neoforge-${neoforgeVersion}-installer.jar`
      await downloadJar(config, signal, dir, url, `neoforge-${neoforgeVersion}-installer.jar`, overwrite, undefined, written, notes)
      notes.push('已下载 NeoForge 安装器；请执行 java -jar neoforge-*-installer.jar --installServer，然后运行 start.sh。')
    } else {
      notes.push('首次部署：下载 https://maven.neoforged.net/releases/net/neoforged/neoforge/ 对应版本的 installer 并 --installServer。')
    }
  }

  if (kind === 'fabric') {
    const loaderVersion = opts.loaderVersion ?? (await fabricLoaderVersions(config, gameVersion, signal, 1)).items[0]?.version
    if (!loaderVersion) throw new Error(`无法确定 Fabric Loader ${gameVersion} 的版本，请显式传入 loaderVersion`)
    const launcherUrl = `https://meta.fabricmc.net/v2/versions/loader/${encodeURIComponent(gameVersion)}/${encodeURIComponent(loaderVersion)}/server/jar`
    fileName = 'fabric-server-launch.jar'
    if (downloadJarOption) {
      const ok = await downloadJar(config, signal, dir, launcherUrl, fileName, overwrite, undefined, written, notes)
      if (!ok) notes.push(`Fabric 服务端启动器下载地址：${launcherUrl}`)
    } else {
      notes.push(`Fabric 服务端启动器：${launcherUrl}（保存为 ${fileName}）。`)
    }
    notes.push(`Fabric Loader 版本：${loaderVersion}（Minecraft ${gameVersion}）。`)
  }

  if (kind === 'paper') {
    fileName = 'paper.jar'
    if (downloadJarOption) {
      const builds = await paperBuilds(config, gameVersion, signal, 'paper')
      const build = builds[0]
      if (build?.url && build.name) {
        fileName = build.name
        const ok = await downloadJar(config, signal, dir, build.url, build.name, overwrite, build.sha256, written, notes)
        if (!ok) fileName = 'paper.jar'
      } else {
        notes.push('未能解析 Paper 构建，请从 https://fill.papermc.io/v3/projects/paper 下载。')
      }
    } else {
      notes.push('请从 https://fill.papermc.io/v3/projects/paper 下载 Paper 1.21.1 最新构建并保存为 paper.jar，或改用 downloadJar: true。')
    }
  }

  if (kind === 'arclight') {
    const variant = opts.arclightVariant ?? (config.defaultLoader === 'fabric' ? 'fabric' : 'neoforge')
    const release = (await arclightReleases(config, gameVersion, signal, variant)).items[0]
    if (release) {
      fileName = release.filename
      if (downloadJarOption) {
        await downloadJar(config, signal, dir, release.url, release.filename, overwrite, undefined, written, notes)
      }
      notes.push(`Arclight 构建：${release.filename}（${release.channel}）。混合端请按官方 README 准备 NeoForge 运行库：https://github.com/IzzelAliz/Arclight`)
    } else {
      notes.push(`没有找到 Arclight ${gameVersion}/${variant} 构建，请查看 https://github.com/IzzelAliz/Arclight/releases。`)
    }
  }

  const scripts = startScripts(kind, { settings, fileName, neoforgeArgsPath })
  written.push(await writeText(dir, 'start.sh', scripts.sh, overwrite))
  written.push(await writeText(dir, 'start.bat', scripts.bat, overwrite))
  for (const entry of written) {
    if (entry.path.endsWith('.sh') && entry.status !== 'skipped' && entry.status !== 'unchanged') {
      try {
        await chmod(join(dir, entry.path), 0o755)
      } catch {
        /* best effort */
      }
    }
  }

  return { dir, kind, gameVersion, files: written, notes: [...new Set(notes)] }
}
