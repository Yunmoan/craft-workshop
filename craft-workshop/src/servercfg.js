function deepMerge(base, patch) {
  if (patch === undefined || patch === null) return base
  if (typeof base !== 'object' || base === null || Array.isArray(base)) return patch
  const out = { ...base }
  for (const [key, value] of Object.entries(patch)) {
    out[key] =
      key in base && typeof base[key] === 'object' && base[key] !== null && !Array.isArray(base[key])
        ? deepMerge(base[key], value)
        : value
  }
  return out
}

/** Escape a value for a Java .properties file (non-ASCII -> \\uXXXX). */
export function propertyValue(value) {
  let out = ''
  for (const ch of String(value ?? '')) {
    const code = ch.codePointAt(0)
    if (ch === '\\') out += '\\\\'
    else if (ch === '\n') out += '\\n'
    else if (ch === '\r') out += '\\r'
    else if (ch === '\t') out += '\\t'
    else if (code < 0x20 || code > 0x7e) out += `\\u${code.toString(16).padStart(4, '0')}`
    else out += ch
  }
  return out
}

function yamlString(value) {
  return `'${String(value ?? '').replace(/'/g, "''")}'`
}

function tomlString(value) {
  return JSON.stringify(String(value ?? ''))
}

/**
 * `pvp` / `enable-command-block` / `allow-nether` were removed from server.properties
 * in 1.21.9 (25w35a) and replaced by game rules; only write them for older targets.
 */
export function hasLegacyCombatProperties(gameVersion) {
  const parts = String(gameVersion ?? '').split('.').map(Number)
  if (!Number.isFinite(parts[0])) return true
  if (parts[0] >= 26) return false
  if (parts[0] !== 1) return true
  const minor = parts[1] ?? 0
  const patch = parts[2] ?? 0
  return minor < 21 || (minor === 21 && patch < 9)
}

